// Package migrator is a reference client of the routing and admission RPCs of the default
// primary (GetRoutingState, StartFence, CommitFence, UnfenceScope, SwitchRouting,
// RevertRouting, FoldRouting, CleanupOperation). It is optional: the RPCs are primitives that
// are safe by construction and report facts, and the policy around them is the migration
// controller's. This package is one such policy, as a set of standard workflows a controller
// can use or replace.
//
// A Migrator runs one operation: it passes the same operation_id, a UUID, to every call
// (Config.OperationID, or one generated by New; see Migrator.OperationID), so a cutover, a
// rollback, a fold and the cleanup of one migration must go through the same Migrator, or
// through Migrators given the same OperationID. The workflows are:
//
//   - Preflight runs the checks that must hold before anything is fenced.
//   - FenceOrGiveUp starts the fence of a tablegroup and asks CommitFence every RetryInterval
//     until it succeeds, logging what holds it up (busy members, with the reservations that
//     hold them); when GiveUpAfter has passed it unfences the tablegroup. Optionally it ends
//     reservations that have been idle too long (TerminateIdle), which is the policy of this
//     library and not something the RPCs do.
//   - UnfenceUntilReached unfences, and repeats until every member was reached.
//   - OnCutoverError and OnRollbackError are the on-error policy for a caller that lost
//     track of a move (a crashed migrator's successor): read the routing state, and decide
//     relative to the move: traffic still where it was, unfence the sides the move fenced;
//     traffic on the side it went to, that side serves and the other stays fenced.
//     Cutover and Rollback apply the same policy themselves, to the sides they fenced.
//   - Cutover and Rollback are the sequences, with the data movement left to the caller.
//     Cutover fences both sides, runs the caller's catch-up, switches the routing and unfences
//     the destination. Rollback fences both sides again, reverts the routing and unfences the
//     source. They refuse a side that is already fenced when they start (a fence held by
//     another operation is never theirs; one of this operation is an earlier attempt, and is
//     taken over only when Steps.Resume says to), unfence only what they fenced, and repeat a
//     routing change whose outcome is unknown until it answers definitively, which is safe
//     because a routing change that already committed succeeds when asked again.
//   - Complete folds the switched rule into the catalog, and Cleanup deletes the operation's
//     fences, in that order and with a decommissioning of the source in between: see their
//     documentation.
//
// Versions are never computed here. A scope that has no fence is at version 0, and a fence
// held by another operation that is UNFENCED is taken over by passing the version read; a fence
// of another operation that is FENCING or FENCED is an error that is surfaced
// (ErrHeldByAnotherOperation).
//
// A migrator holds no open transaction and no running statement of its own on the source
// while a fence is in progress: they are application work the fence waits for. It reads the
// catch-up position after the fence returns, from the source (pg_current_wal_insert_lsn() on
// a connection that is closed again, or IDENTIFY_SYSTEM on a replication connection), because
// nothing more is written through the fenced poolers from then on and the fence itself
// returns none. Replication connections through the pooler are assumed to carry only
// replication.
//
// The fence covers what goes through the pooler and nothing else. That every application and
// platform writer goes through it, and that the writers that cannot (scheduled jobs,
// background workers on the source) have been stopped, is a precondition of a cutover that
// the workflow around this package meets: direct connections to the source are neither
// fenced nor looked for. A commit refused by an idle session converges when asked again after
// the reserved pool's inactivity timeout (30 seconds by default), so GiveUpAfter should be
// longer than that, unless TerminateIdle ends such sessions sooner.
//
// Everything here only calls the RPCs. How long to wait, whether to retry, and what to
// catch the destination up to (the migrator reads its own target, for instance
// pg_current_wal_insert_lsn() on the fenced source) are its settings and callbacks.
//
// PROTOTYPE STUB: a test client of the prototype RPCs.
package migrator

